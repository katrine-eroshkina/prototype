/**
 * Черновые тексты прототипа. Правила (войдут в инструкцию):
 *   заголовок блока — до 8 слов; лид — до 20 слов;
 *   карточка — заголовок до 5 слов + одна строка до 12 слов.
 * Цифры и цены — заглушки «XX», заменяются данными заказчика.
 */
import type { GroupSlug } from './sitemap';

export type DirectionSlug = GroupSlug;
export type PageKind =
  | 'home' | 'catalog' | 'category' | 'service'
  | 'casesList' | 'case' | 'about' | 'prices' | 'contacts' | 'blog' | 'text' | 'system';

export interface Crumb { href?: string; title: string }
export interface LinkItem { href: string; title: string; text?: string; draft?: boolean }

/** Контекст страницы — по нему блоки подбирают тексты */
export interface PageCtx {
  kind: PageKind;
  title: string;
  crumbs?: Crumb[];
  direction?: DirectionSlug;
  category?: { slug: string; title: string };
  children?: LinkItem[];
}

